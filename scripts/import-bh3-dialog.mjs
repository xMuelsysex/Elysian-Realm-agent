import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SITE_ORIGIN = "https://www.bh3text.com";
const INDEXES = [
  { arcId: "elysian-realm", chapterId: "er-1", path: "/dialog/er/1/" },
  { arcId: "elysian-realm", chapterId: "er-2", path: "/dialog/er/2/" },
  { arcId: "elysian-realm", chapterId: "er-3", path: "/dialog/er/3/" },
  { arcId: "to-the-flawless", chapterId: "mainline-29", path: "/dialog/mainline/1/29/" },
  { arcId: "to-the-flawless", chapterId: "mainline-30", path: "/dialog/mainline/1/30/" },
  { arcId: "to-the-flawless", chapterId: "mainline-31", path: "/dialog/mainline/1/31/" },
];
const OUTPUT = join("src", "lore", "elysianRealmDialogue.ts");
const SOURCE_HEADER = `// Generated by scripts/import-bh3-dialog.mjs.\n// Source: https://www.bh3text.com/dialog/\n// This file is a local, read-only story snapshot; runtime code never fetches the site.\n\nimport type { LoreDialogueCatalogV1 } from "./loreDialogueRecords.js";\n\n`;

const htmlEntities = new Map([
  ["amp", "&"],
  ["lt", "<"],
  ["gt", ">"],
  ["quot", '"'],
  ["apos", "'"],
  ["nbsp", " "],
]);

class HttpError extends Error {
  constructor(status, url) {
    super(`fetch failed (${status}) ${url}`);
    this.status = status;
  }
}

function decodeHtml(value) {
  return value
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(Number.parseInt(hex, 16)))
    .replace(/&#([0-9]+);/g, (_, decimal) => String.fromCodePoint(Number.parseInt(decimal, 10)))
    .replace(/&([a-z]+);/gi, (match, name) => htmlEntities.get(name.toLowerCase()) ?? match);
}

function textFromHtml(value) {
  return decodeHtml(
    value
      .replace(/<br\s*\/?>/gi, "\n")
      .replace(/<[^>]+>/g, "")
      .replace(/\s+$/g, ""),
  ).trim();
}

function attribute(markup, name) {
  const match = new RegExp(`${name}="([^"]*)"`, "i").exec(markup);
  return match ? decodeHtml(match[1]) : undefined;
}

async function fetchHtml(path) {
  const url = new URL(path, SITE_ORIGIN).toString();
  const response = await fetch(url);
  if (!response.ok) throw new HttpError(response.status, url);
  const html = await response.text();
  if (html.length === 0) throw new Error(`empty response ${url}`);
  return { html, url };
}

function pageTitle(html, fallback) {
  const title = /<h1[^>]*id="page-title"[^>]*>([\s\S]*?)<\/h1>/i.exec(html)?.[1]
    ?? /<main[^>]*>[\s\S]*?<h1[^>]*>([\s\S]*?)<\/h1>/i.exec(html)?.[1];
  return title ? textFromHtml(title) : fallback;
}

function indexLinks(html, indexPath) {
  const main = /<main\b[^>]*id="main-content"[^>]*>([\s\S]*?)<\/main>/i.exec(html)?.[1];
  if (!main) throw new Error(`missing main content ${indexPath}`);
  const prefix = new URL(indexPath, SITE_ORIGIN).pathname;
  const links = [];
  for (const match of main.matchAll(/<li>\s*<a\b[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>\s*<\/li>/gi)) {
    const url = new URL(match[1], SITE_ORIGIN);
    if (url.pathname.startsWith(prefix) && url.pathname !== prefix) {
      links.push({ path: `${url.pathname}${url.search}${url.hash}`, title: textFromHtml(match[2]) });
    }
  }
  const seen = new Set();
  return links.filter((link) => !seen.has(link.path) && seen.add(link.path));
}

function markerKind(marker) {
  if (/(?:成功|失败|得分|结果|挑战)/.test(marker)) return "result";
  if (/(?:同行|选择|出手|不出手|路线|分支)/.test(marker)) return "branch";
  return "route";
}

function innerSpanByClass(markup, className) {
  const openPattern = /<span\b[^>]*class="([^"]*)"[^>]*>/gi;
  let match;
  while ((match = openPattern.exec(markup)) !== null) {
    if (!match[1].split(/\s+/).includes(className)) continue;
    const contentStart = openPattern.lastIndex;
    const tags = /<\/?span\b[^>]*>/gi;
    tags.lastIndex = contentStart;
    let depth = 1;
    let tag;
    while ((tag = tags.exec(markup)) !== null) {
      if (tag[0].startsWith("</")) {
        depth -= 1;
      } else if (!tag[0].endsWith("/>")) {
        depth += 1;
      }
      if (depth === 0) return markup.slice(contentStart, tag.index);
    }
    return undefined;
  }
  return undefined;
}

function parseLineType(rawLine, title, contentMarkup = innerSpanByClass(rawLine, "dialog-content") ?? "") {
  if (/class="[^"]*dialog-system[^"]*"/i.test(rawLine)) return "system";
  if (/class="[^"]*d-option[^"]*"/i.test(rawLine)) return "option";

  const color = /color\s*:\s*(#[0-9a-f]{6})/i.exec(contentMarkup)?.[1]?.toLowerCase();
  const text = textFromHtml(contentMarkup);
  if (color === "#6c437a" || color === "#601986") return "option";
  if (color === "#61468f" && text !== "（回忆）") return "annotation";
  if (/(?:结果|成功|失败|完成)/.test(title)) return "annotation";
  return "narration";
}

function parseLines(stageHtml, sceneId, stageId, title) {
  const lines = [];
  const pattern = /<div\s+class="content\s+dialog-line"\s+id="content_(\d+)_(\d+)"[^>]*>([\s\S]*?)<\/div>/gi;
  for (const match of stageHtml.matchAll(pattern)) {
    const sourceIndex = Number(match[2]);
    const rawLine = match[3];
    const actor = innerSpanByClass(rawLine, "dialog-actor");
    const content = innerSpanByClass(rawLine, "dialog-content");
    if (content === undefined) continue;
    const text = textFromHtml(content);
    if (text.length === 0) continue;
    const speaker = actor === undefined ? undefined : textFromHtml(actor);
    const parsedKind = parseLineType(rawLine, title, content);
    lines.push({
      id: `${sceneId}:${stageId}:${sourceIndex}`,
      stageId,
      sourceIndex,
      kind: speaker !== undefined && parsedKind !== "option" ? "dialogue" : parsedKind,
      ...(speaker !== undefined ? { speaker } : {}),
      text,
    });
  }
  return lines;
}

function parseStages(html, sceneId, title) {
  const stages = [];
  const stagePattern = /<section\s+class="stage"\s+id="([^"]+)"[^>]*>([\s\S]*?)<\/section>/gi;
  for (const match of html.matchAll(stagePattern)) {
    const stageId = match[1];
    const stageHtml = match[2];
    const lines = parseLines(stageHtml, sceneId, stageId, title);
    const markerMarkup = stageHtml
      .replace(/<div\s+class="content\s+dialog-line"[^>]*>[\s\S]*?<\/div>/gi, "")
      .replace(/<cg-viewer\b[\s\S]*?<\/cg-viewer>/gi, "");
    const marker = textFromHtml(markerMarkup);
    const cgMarkup = /<cg-viewer\b([^>]*)>([\s\S]*?)<\/cg-viewer>/i.exec(stageHtml);
    const mediaLink = cgMarkup?.[2] === undefined
      ? undefined
      : /<a\b[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/i.exec(cgMarkup[2]);
    const media = cgMarkup
      ? {
          ...(attribute(cgMarkup[1], "cg") !== undefined ? { cg: attribute(cgMarkup[1], "cg") } : {}),
          ...(mediaLink ? { displayName: textFromHtml(mediaLink[2]), href: new URL(mediaLink[1], SITE_ORIGIN).toString() } : {}),
        }
      : undefined;
    stages.push({
      id: stageId,
      ...(marker.startsWith("【") ? { marker, markerKind: markerKind(marker) } : {}),
      lines,
      ...(media !== undefined ? { media } : {}),
    });
  }
  if (stages.length === 0) throw new Error(`no stages found in ${sceneId}`);
  if (stages.every((stage) => stage.lines.length === 0 && stage.media === undefined)) {
    throw new Error(`no text or media found in ${sceneId}`);
  }
  return stages;
}

async function fetchScenes(index, diagnostics) {
  const { html } = await fetchHtml(index.path);
  const links = indexLinks(html, index.path);
  if (links.length === 0) throw new Error(`no scene links found in ${index.path}`);
  const scenes = [];
  for (let offset = 0; offset < links.length; offset += 8) {
    const fetched = await Promise.all(links.slice(offset, offset + 8).map(async (link, batchIndex) => {
      try {
        const { html: sceneHtml, url } = await fetchHtml(link.path);
        const id = `bh3-${index.chapterId}-${String(offset + batchIndex + 1).padStart(3, "0")}`;
        const title = pageTitle(sceneHtml, link.title);
        return {
          id,
          arcId: index.arcId,
          chapterId: index.chapterId,
          order: 0,
          title,
          sourceUrl: url,
          available: true,
          stages: parseStages(sceneHtml, id, title),
        };
      } catch (error) {
        if (error instanceof HttpError && error.status === 404) {
          diagnostics.push({ sourceUrl: error.message.replace(/^fetch failed \(404\) /, ""), status: 404, message: "source page is listed by the index but is unavailable" });
          return {
            id: `bh3-${index.chapterId}-${String(offset + batchIndex + 1).padStart(3, "0")}`,
            arcId: index.arcId,
            chapterId: index.chapterId,
            order: 0,
            title: link.title,
            sourceUrl: new URL(link.path, SITE_ORIGIN).toString(),
            available: false,
            stages: [],
          };
        }
        throw error;
      }
    }));
    scenes.push(...fetched);
    console.log(`${index.chapterId}: ${Math.min(offset + 8, links.length)}/${links.length}`);
  }
  return { title: pageTitle(html, index.chapterId), scenes };
}

const diagnostics = [];
const chapters = [];
for (const index of INDEXES) {
  chapters.push({ ...index, ...(await fetchScenes(index, diagnostics)) });
}
const scenes = chapters.flatMap((chapter) => chapter.scenes);
scenes.forEach((scene, index) => { scene.order = index; });
const catalog = {
  schemaVersion: "lore-dialogue.v1",
  source: "https://www.bh3text.com/dialog/",
  arcs: [
    { id: "elysian-realm", title: "往世乐土", chapterIds: chapters.filter((chapter) => chapter.arcId === "elysian-realm").map((chapter) => chapter.chapterId) },
    { id: "to-the-flawless", title: "致以无瑕之人", chapterIds: chapters.filter((chapter) => chapter.arcId === "to-the-flawless").map((chapter) => chapter.chapterId) },
  ],
  chapters: chapters.map(({ scenes: chapterScenes, path: _path, chapterId, ...chapter }) => ({
    ...chapter,
    id: chapterId,
    sceneIds: chapterScenes.map((scene) => scene.id),
  })),
  scenes,
  ...(diagnostics.length > 0 ? { diagnostics } : {}),
};

mkdirSync(join("src", "lore"), { recursive: true });
writeFileSync(OUTPUT, `${SOURCE_HEADER}export const ELYSIAN_REALM_DIALOGUE: LoreDialogueCatalogV1 = ${JSON.stringify(catalog, null, 2)};\n`);
const lineCount = scenes.reduce((total, scene) => total + scene.stages.reduce((stageTotal, stage) => stageTotal + stage.lines.length, 0), 0);
console.log(`wrote ${scenes.length} scenes and ${lineCount} lines to ${OUTPUT}`);
if (diagnostics.length > 0) console.warn(`recorded ${diagnostics.length} unavailable source page(s)`);
