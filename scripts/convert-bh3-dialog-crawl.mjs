import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2] ?? ".bh3-dialogue-crawl.json";
const target = process.argv[3] ?? "src/lore/elysianRealmDialogue.ts";
const catalog = JSON.parse(readFileSync(source, "utf8"));
const header = `// Generated by scripts/import-bh3-dialog.mjs.\n// Source: https://www.bh3text.com/dialog/\n// This file is a local, read-only story snapshot; runtime code never fetches the site.\n\nimport type { LoreDialogueCatalogV1 } from "./loreDialogueRecords.js";\n\n`;

// Keep an unavailable index entry as an explicit locked scene. This preserves
// the source order and cursor positions without inventing missing dialogue.
const unavailablePositions = new Map([
  ["https://www.bh3text.com/dialog/er/3/%E6%90%9C%E5%AF%BB%C2%B7%E5%85%B6%E4%B8%80", 13],
  ["https://www.bh3text.com/dialog/er/3/%E6%89%93%E5%AD%97%E6%9C%BA-%E6%AD%BB%E6%9C%9F%E5%8D%81%E6%97%A5%E5%8D%B3%E8%87%B3", 68],
  ["https://www.bh3text.com/dialog/er/3/%E6%89%93%E5%AD%97%E6%9C%BA-%E4%BF%AF%E7%9E%B0%E5%91%BD%E8%BF%90%E4%B9%8B%E4%BA%BA", 76],
]);
const diagnostics = catalog.diagnostics ?? [];
const sceneGroups = new Map();
for (const chapter of catalog.chapters) {
  sceneGroups.set(chapter.id, catalog.scenes.filter((scene) => scene.chapterId === chapter.id));
}
for (const diagnostic of diagnostics) {
  if (diagnostic.status < 400) continue;
  const chapterId = diagnostic.sourceUrl.includes("/dialog/er/3/") ? "er-3" : undefined;
  if (chapterId === undefined) continue;
  const scenes = sceneGroups.get(chapterId) ?? [];
  const position = unavailablePositions.get(diagnostic.sourceUrl) ?? scenes.length + 1;
  if (scenes.some((scene) => scene.sourceUrl === diagnostic.sourceUrl)) continue;
  const sceneId = `bh3-${chapterId}-${String(position).padStart(3, "0")}`;
  const title = decodeURIComponent(diagnostic.sourceUrl.split("/").at(-1) ?? sceneId);
  scenes.splice(position - 1, 0, {
    id: sceneId,
    arcId: "elysian-realm",
    chapterId,
    order: 0,
    title,
    sourceUrl: diagnostic.sourceUrl,
    available: false,
    stages: [],
  });
}
const scenes = [...sceneGroups.values()].flat();
scenes.forEach((scene, index) => {
  scene.order = index;
  if (scene.available === undefined) scene.available = true;
});
const normalized = {
  ...catalog,
  chapters: catalog.chapters.map((chapter) => ({
    ...chapter,
    sceneIds: (sceneGroups.get(chapter.id) ?? []).map((scene) => scene.id),
  })),
  scenes,
};
writeFileSync(target, `${header}export const ELYSIAN_REALM_DIALOGUE: LoreDialogueCatalogV1 = ${JSON.stringify(normalized, null, 2)};\n`);
console.log(`wrote ${scenes.length} scenes to ${target}`);
